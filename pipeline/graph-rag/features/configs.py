"""
features/configs.py — Feature category definitions and LLM settings for the
                       third graph layer (Feature Extraction)

Why is this file separate from vocabulary_categorizer.py?
    These settings (category names, descriptions, LLM model) are needed in
    several places: the one-time vocabulary categorization step, and later
    in extractor.py (per-ruling feature extraction). Same pattern as
    laws/configs.py, used by both parser.py and main_cases.py.

Why is "Referenced Articles" not defined here?
    Per an earlier decision, that feature is already extracted with regex
    in cases/parser.py (cited_articles / text_cited_articles) and should
    not be regenerated by an LLM. This file only covers categories that
    genuinely need one.

Why is "Legal Facts" a separate category with no closed vocabulary?
    Facts (e.g. "payment was not made") are unboundedly varied and can't be
    enumerated in advance; they must be extracted freely from the text
    (with an evidence span, per the original design). That's why it's not
    in VOCAB_CATEGORIES — it's not meant to be classified against an
    existing vocabulary.

    Note: linking a Fact (when relevant) to a structured node (Role/
    Action/Object) was proposed and deliberately rejected — a Fact must
    always stay as free, complete text, with no link or dependency on the
    closed vocabulary, so case information isn't pruned.

Why is normalization/alias resolution done in the same categorization
pass, not a separate second pass?
    A second pass would mean sending the whole vocabulary to the LLM again
    — double the cost for something the LLM can do at the same time as
    categorization. So in vocabulary_categorizer.py, alongside "category",
    a "root" (canonical form) field is also requested: e.g. "عقد بیع" and
    "قرارداد بیع" both return category=concept and root="بیع".

Why was "principle" dropped?
    In practice (per vocabulary_categorizer.py's report), out of 377 raw
    terms only 6 were genuinely meaningful legal principles (98% noise —
    connectives and adverbs like "با توجه به", "مستنداً", "هرچند"). Those
    6 remaining terms were manually moved into concept aliases; this
    category is no longer extracted by the pipeline.

LLM provider:
    A single provider — OpenRouter — is used for the whole pipeline, with
    the model set in OPENROUTER_MODEL below. There is no fallback chain;
    if the call fails, get_llm_client()'s client raises and the caller's
    own retry loop (see extractor.py / vocabulary_categorizer.py) handles it.
"""

