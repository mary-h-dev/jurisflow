LLM_TEMPERATURE = 0.1
MAX_OUTPUT_TOKENS = 6000

# Model actually used for this project's runs.
OPENROUTER_MODEL = "models/gemini-2.6-flash"

# Kept for logging/back-compat with code that imports LLM_MODEL directly.
LLM_MODEL = OPENROUTER_MODEL


class _ChatClient:
    """
    Presents the same interface extractor.py / vocabulary_categorizer.py
    expect from an OpenAI-compatible client
    (`_client.chat.completions.create(model=..., messages=..., temperature=...)`,
    reading `response.choices[0].message.content`), backed by a single
    OpenRouter call. No fallback to other providers — if the request
    fails, it raises and the caller's own retry loop handles it.
    """

    class _Msg:
        def __init__(self, content):
            self.content = content

    class _Choice:
        def __init__(self, content):
            self.message = _ChatClient._Msg(content)

    class _Response:
        def __init__(self, content):
            self.choices = [_ChatClient._Choice(content)]

    class _Completions:
        def __init__(self, call_fn):
            self._call_fn = call_fn  # (prompt, temperature) -> str

        def create(self, model: str, messages: list[dict], temperature: float = 0.1, **_):
            prompt = messages[0]["content"]
            text = self._call_fn(prompt, temperature)
            return _ChatClient._Response(text)

    def __init__(self, call_fn):
        self.chat = self
        self.completions = self._Completions(call_fn)


def _make_openrouter_call():
    """
    OpenRouter call (OpenAI-compatible proxy). Requires OPENROUTER_API_KEY
    in .env (get one at https://openrouter.ai/keys).
    """
    from openai import OpenAI

    client = OpenAI(base_url="https://openrouter.ai/api/v1", api_key=os.getenv("OPENROUTER_API_KEY"))

    def call(prompt: str, temperature: float) -> str:
        response = client.chat.completions.create(
            model=OPENROUTER_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=temperature,
            max_tokens=MAX_OUTPUT_TOKENS,
        )
        return response.choices[0].message.content

    return call


def get_llm_client():
    """
    Shared LLM client for all features/ modules (vocabulary_categorizer.py,
    extractor.py). Single provider: OpenRouter, model OPENROUTER_MODEL.

    Requires OPENROUTER_API_KEY in .env — https://openrouter.ai/keys
    """
    if not os.getenv("OPENROUTER_API_KEY"):
        raise RuntimeError("OPENROUTER_API_KEY is not set in .env.")

    print(f"🔌 LLM provider: openrouter (model={OPENROUTER_MODEL})")
    return _ChatClient(_make_openrouter_call())


